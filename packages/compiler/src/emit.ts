import { createHash } from "node:crypto";
import { format } from "prettier";
import type { Column, Ir, IrEntity } from "./ir.js";
import { staticTemplates } from "./static-templates.js";
import { isGeneratedPath, isUserPath } from "./zones.js";

export type Zone = "generated" | "user";
export type OutFile = { path: string; contents: string; zone: Zone };
export type FileSet = ReadonlyArray<OutFile>;

export const prettierVersion = "3.9.10";
const prettierOptions = { printWidth: 120, tabWidth: 2, useTabs: false, semi: true, singleQuote: false, trailingComma: "all", endOfLine: "lf" } as const;

const header = "Generated by owninfra generate. Do not edit: changes are overwritten and a hand edit makes generate refuse.";

export const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
export const irHash = (ir: Ir) => sha256(JSON.stringify(ir));

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const literal = (v: string | number | boolean) => (typeof v === "string" ? q(v) : String(v));

function columnSql(c: Column): string {
  const parts = [`"${c.name}"`, c.sql];
  if (c.required) parts.push("not null");
  if (c.unique) parts.push("unique");
  if (c.default !== null) parts.push(`default ${literal(c.default)}`);
  const checks: string[] = [];
  if (c.values) checks.push(`"${c.name}" in (${c.values.map(q).join(", ")})`);
  if (c.pattern) checks.push(`"${c.name}" ~ ${q(c.pattern)}`);
  if (c.min !== null && (c.input === "int" || c.input === "decimal")) checks.push(`"${c.name}" >= ${c.min}`);
  if (c.max !== null && (c.input === "int" || c.input === "decimal")) checks.push(`"${c.name}" <= ${c.max}`);
  if (checks.length) parts.push(`check (${checks.join(" and ")})`);
  return parts.join(" ");
}

function tableSql(e: IrEntity): string {
  const cols = [
    `"id" uuid primary key default gen_random_uuid()`,
    ...e.columns.map(columnSql),
    ...(e.workflow
      ? [`"${e.workflow.field}" text not null default ${q(e.workflow.initial)} check ("${e.workflow.field}" in (${e.workflow.states.map((s) => q(s.id)).join(", ")}))`]
      : []),
    `"created_at" timestamptz not null default now()`,
    `"updated_at" timestamptz not null default now()`,
    `"created_by" text not null`,
  ];
  return `create table "${e.table}" (\n  ${cols.join(",\n  ")}\n);\n`;
}

export function migrationSql(ir: Ir): string {
  const fks = ir.entities.flatMap((e) =>
    e.columns.filter((c) => c.ref).map((c) => `alter table "${e.table}" add foreign key ("${c.name}") references "${c.ref}" ("id");\n`),
  );
  const audit = ir.audit.enabled
    ? [
        `create table "audit_events" (\n  "id" bigserial primary key,\n  "at" timestamptz not null default now(),\n  "actor" text not null,\n  "entity" text not null,\n  "entity_id" uuid not null,\n  "action" text not null,\n  "before" jsonb,\n  "after" jsonb\n);\n`,
        `create index on "audit_events" ("entity", "entity_id");\n`,
      ]
    : [];
  return [`-- ${header}\n`, ...ir.entities.map(tableSql), ...fks, ...audit].join("\n");
}

function drizzleColumn(c: Column): string {
  const builder = {
    string: c.max !== null ? `varchar("${c.name}", { length: ${c.max} })` : `text("${c.name}")`,
    text: `text("${c.name}")`,
    email: `text("${c.name}")`,
    int: `integer("${c.name}")`,
    decimal: c.precision !== null ? `numeric("${c.name}", { precision: ${c.precision}, scale: ${c.scale ?? 0} })` : `numeric("${c.name}")`,
    bool: `boolean("${c.name}")`,
    date: `date("${c.name}")`,
    datetime: `timestamp("${c.name}", { withTimezone: true })`,
    enum: `text("${c.name}", { enum: ${JSON.stringify(c.values)} })`,
    ref: `uuid("${c.name}")`,
  }[c.input];
  const chain = [builder];
  if (c.required) chain.push("notNull()");
  if (c.unique) chain.push("unique()");
  if (c.default !== null) chain.push(`default(${JSON.stringify(c.input === "decimal" ? String(c.default) : c.default)})`);
  if (c.ref) chain.push(`references(() => ${c.ref}.id)`);
  return `${JSON.stringify(c.name)}: ${chain.join(".")}`;
}

export function drizzleSchema(ir: Ir): string {
  const tables = ir.entities.map((e) => {
    const cols = [
      `id: uuid("id").primaryKey().defaultRandom()`,
      ...e.columns.map(drizzleColumn),
      ...(e.workflow ? [`${JSON.stringify(e.workflow.field)}: text("${e.workflow.field}", { enum: ${JSON.stringify(e.workflow.states.map((s) => s.id))} }).notNull().default(${JSON.stringify(e.workflow.initial)})`] : []),
      `created_at: timestamp("created_at", { withTimezone: true }).notNull().defaultNow()`,
      `updated_at: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow()`,
      `created_by: text("created_by").notNull()`,
    ];
    return `export const ${e.table} = pgTable("${e.table}", {\n${cols.join(",\n")}\n});`;
  });
  const audit = ir.audit.enabled
    ? `export const audit_events = pgTable("audit_events", { id: bigserial("id", { mode: "number" }).primaryKey(), at: timestamp("at", { withTimezone: true }).notNull().defaultNow(), actor: text("actor").notNull(), entity: text("entity").notNull(), entity_id: uuid("entity_id").notNull(), action: text("action").notNull(), before: jsonb("before"), after: jsonb("after") });`
    : "";
  const body = `${tables.join("\n\n")}\n\n${audit}\n`;
  const used = ["bigserial", "boolean", "date", "integer", "jsonb", "numeric", "pgTable", "text", "timestamp", "uuid", "varchar"].filter((b) => body.includes(`${b}(`));
  return `// ${header}\nimport { ${used.join(", ")} } from "drizzle-orm/pg-core";\n\n${body}`;
}

export function registrySource(ir: Ir): string {
  const registry = {
    app: ir.app,
    roles: ir.roles,
    entities: ir.entities.map((e) => ({
      ...e,
      columns: e.columns.map(({ name, label, input, required, unique, ref, values, default: d, min, max, pattern, precision, scale }) => ({
        name, label, input, required, unique, ref, values, default: d, min, max, pattern, precision, scale,
      })),
    })),
    policies: ir.policies,
    seedUsers: ir.seedUsers,
    audit: ir.audit,
  };
  return `// ${header}\nimport type { Registry } from "./types";\n\nexport const registry: Registry = ${JSON.stringify(registry, null, 2)};\n`;
}

function compose(ir: Ir): string {
  return `# ${header}
services:
  postgres:
    image: postgres:16
    environment:
      POSTGRES_USER: owninfra
      POSTGRES_PASSWORD: owninfra
      POSTGRES_DB: ${ir.app.name.replace(/-/g, "_")}
    ports:
      - "5432:5432"
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U owninfra"]
      interval: 2s
      timeout: 2s
      retries: 30
`;
}

export const databaseUrl = (ir: Ir) => `postgres://owninfra:owninfra@localhost:5432/${ir.app.name.replace(/-/g, "_")}`;

const reservedPrefixes = ["/api/auth", "/api/e", "/api/audit", "/e", "/inbox", "/admin/audit"];

export function routeOf(path: string): string | null {
  const m = /^app\/src\/app\/(.*)\/(page\.tsx|route\.ts)$/.exec(path) ?? (/^app\/src\/app\/(page\.tsx)$/.test(path) ? ["", ""] : null);
  if (!m) return null;
  return "/" + m[1].split("/").filter((s) => s && !/^\(.*\)$/.test(s)).join("/");
}

function check(files: OutFile[]) {
  const seen = new Map<string, Zone>();
  for (const f of files) {
    if (seen.has(f.path)) throw new Error(`emit: '${f.path}' emitted twice`);
    seen.set(f.path, f.zone);
    if (f.zone === "user" && (!isUserPath(f.path) || isGeneratedPath(f.path))) throw new Error(`emit: user file '${f.path}' is outside the user zone`);
    if (f.zone === "generated" && (!isGeneratedPath(f.path) || isUserPath(f.path))) throw new Error(`emit: generated file '${f.path}' is outside the generated zone`);
  }
  const routes = new Map<string, string>();
  for (const f of files) {
    const r = routeOf(f.path);
    if (r === null) continue;
    const kind = f.path.endsWith("route.ts") ? "api" : "page";
    const key = `${kind} ${r}`;
    if (routes.has(key)) throw new Error(`emit: route ${r} is produced by both '${routes.get(key)}' and '${f.path}'`);
    routes.set(key, f.path);
    if (f.zone === "user" && reservedPrefixes.some((p) => r === p || r.startsWith(p + "/"))) throw new Error(`emit: user route ${r} collides with a generated route`);
  }
}

const parserFor = (path: string) =>
  /\.(ts|tsx|mts)$/.test(path) ? "typescript" : /\.(mjs|js)$/.test(path) ? "babel" : path.endsWith(".json") ? "json" : null;

function withHeader(path: string, contents: string): string {
  if (/\.(ts|tsx|mts|mjs|js)$/.test(path)) {
    const directive = /^"use (server|client)";\n/.exec(contents);
    return directive ? `${directive[0]}// ${header}\n${contents.slice(directive[0].length)}` : `// ${header}\n${contents}`;
  }
  if (/(^|\/)\.gitignore$|\.gitattributes$|\.ya?ml$/.test(path)) return `# ${header}\n${contents}`;
  return contents;
}

export async function emit(ir: Ir): Promise<FileSet> {
  const dynamic: OutFile[] = [
    { path: "docker-compose.yml", zone: "generated", contents: compose(ir) },
    { path: ".gitattributes", zone: "generated", contents: "* text=auto eol=lf\n" },
    { path: "app/drizzle/0000_init.sql", zone: "generated", contents: migrationSql(ir) },
    { path: "app/drizzle/seed.json", zone: "generated", contents: JSON.stringify(ir.seed) },
    { path: "app/src/lib/(generated)/schema.ts", zone: "generated", contents: drizzleSchema(ir) },
    { path: "app/src/lib/(generated)/registry.ts", zone: "generated", contents: registrySource(ir) },
  ];
  const fixed = staticTemplates.map((t) => ({ ...t, contents: t.zone === "generated" ? withHeader(t.path, t.contents) : t.contents }));
  const all = [...dynamic, ...fixed];
  const files = await Promise.all(
    all.map(async (f) => {
      const parser = parserFor(f.path);
      return parser ? { ...f, contents: await format(f.contents, { ...prettierOptions, parser }) } : f;
    }),
  );
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  check(files);
  return files;
}
